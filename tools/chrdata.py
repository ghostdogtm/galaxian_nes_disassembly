"""Game data that Galaxian keeps in CHR ROM -> src/chr.asm (used by tools/disasm.py).

RESET copies two CHR ranges into RAM (see the notes at $FC50 / $FC82 in src/prg/reset.asm):
  PPU $098E-$0A3F -> RAM $014E-$01FF  songTable (4 tune pointers, PPU addresses) + tunes 1-3
  PPU $1480-$17FF -> RAM $0300-$067F  textPtrs (36 text pointers, PPU addresses) + text records
Both blocks are assembled with .org at their RAM address, so their labels are RAM addresses and the
pointers are written as label + bias; texts and tunes can be edited and change length freely.
PPU $1600-$16FF (RAM $0480-$057F) inside the text block are real tiles $60-$6F (HUD icons) and stay
an .incbin from chr_1.chr, like the rest of the pattern tables.

Text record: screen row, start column in textBuf (column 3 + n), characters up to TEXT_END ('*').
Characters are tile + textCharBias: '0' for the normal font (charmap: ' ' = $40, '-' = $5B, '.' = $5C;
':' ';' '<' '=' '>' '?' are the second-font digits 1 2 4 7 8 9, ']' is (c)), 0 for the logo rows (raw tiles).
Tune: note bytes DUR_n | NOTE_x, the first byte is never played, SONG_END ($FF) ends it.
"""
import re

SONG_CHR, SONG_RAM, SONG_SIZE = 0x098E, 0x014E, 0xB2
TEXT_CHR, TEXT_RAM, TEXT_SIZE = 0x1480, 0x0300, 0x380
TILES_RAM, TILES_END = 0x0480, 0x0580           # tiles $60-$6F inside the text block
TEXT_COUNT = 35
TUNE_NAMES = {1: 'TuneFlagshipHit', 2: 'TuneAlienHit', 3: 'TuneGameStart'}
ALT = {':': '1', ';': '2', '<': '4', '=': '7', '>': '8', '?': '9', ']': '(c)'}
CHARMAP = {0x40: ' ', 0x5B: '-', 0x5C: '.'}
TEXT_END = 0x2A
# names src/chr.asm uses; defined there when const.txt does not have them (generation without labels)
FALLBACK = dict(CHR_SONGS=SONG_CHR, SONG_DATA_SIZE=SONG_SIZE, SONG_PTR_BIAS=SONG_CHR - SONG_RAM, SONG_END=0xFF,
                CHR_TABLE1=0x1000, CHR_GAME_DATA=TEXT_CHR, CHR_GAME_DATA_SIZE=TEXT_SIZE,
                CHR_ICONS=0x1000 + (TILES_RAM - TEXT_RAM + TEXT_CHR - 0x1000), TEXT_PTR_BIAS=TEXT_CHR - TEXT_RAM,
                TEXT_END=TEXT_END)


def camel(s):
    return ''.join(w[:1].upper() + w[1:].lower() for w in re.findall(r'[A-Za-z]+|[0-9]+', s))


def is_char(b):
    return 0x30 <= b <= 0x5D and b not in (0x22, TEXT_END)


def text_parts(body, specials):
    """normal-font record body -> list of ca65 expressions (strings and names)"""
    parts, s = [], ''
    for b in body:
        if is_char(b):
            s += CHARMAP.get(b, chr(b))
            continue
        if s:
            parts.append('"%s"' % s)
            s = ''
        sp = [(n, b - v) for v, n in specials.items() if 0 <= b - v < (3 if n == 'CHAR_PTS' else 1)]
        parts.append(('%s+%d' % sp[0] if sp[0][1] else sp[0][0]) if sp else '$%02X' % b)
    if s:
        parts.append('"%s"' % s)
    return parts


def shown(body, specials):
    out = ''
    for b in body:
        if is_char(b):
            c = CHARMAP.get(b, chr(b))
            out += ALT.get(c, c)
        else:
            out += {'CHAR_COLON': ':'}.get(specials.get(b), '' if specials.get(b - 1, specials.get(b - 2)) == 'CHAR_PTS'
                                           else 'PTS' if specials.get(b) == 'CHAR_PTS' else '?')
    return out


def hexbytes(data):
    return ', '.join('$%02X' % b for b in data)


def generate(chr_, consts, note_names, dur_names):
    """chr_: 8KB CHR; consts: {name: value}. Returns (chr.asm text, {ram addr: (name, size, comment)})."""
    labels = {}
    txt_names = {v: k for k, v in consts.items() if k.startswith('TXT_')}
    specials = {consts[k]: k for k in ('CHAR_PTS', 'CHAR_COLON') if k in consts}
    out = ['; CHR ROM: 2 x 4KB pattern tables (chr/chr_0.chr = PPU $0000, chr/chr_1.chr = PPU $1000)',
           '; with the game data that RESET copies to RAM. Generated by tools/disasm.py (tools/chrdata.py).',
           '; Tiles edited in gfx/sheet_00.png reach the ROM through chr/*.chr; the data blocks below are taken',
           '; from this file, so their bytes in the .chr files / PNG are ignored.',
           '']
    missing = [n for n in FALLBACK if n not in consts]
    if missing:
        out += ['; not in tools/labels/const.txt:'] + ['%-22s = $%04X' % (n, FALLBACK[n]) for n in missing] + ['']
    out += ['.segment "CHR_ROM"', '']

    # ---------------------------------------------------------------- tunes
    blk = chr_[SONG_CHR:SONG_CHR + SONG_SIZE]
    ptrs = [blk[2 * k] | blk[2 * k + 1] << 8 for k in range(4)]
    bias = SONG_CHR - SONG_RAM
    starts = {p - bias: k for k, p in enumerate(ptrs) if p}
    out += ['  .incbin "chr/chr_0.chr", $0000, CHR_SONGS', '',
            '; PPU $%04X-$%04X -> RAM $%04X-$%04X: tune pointers (PPU addresses) + tunes 1-3'
            % (SONG_CHR, SONG_CHR + SONG_SIZE - 1, SONG_RAM, SONG_RAM + SONG_SIZE - 1),
            '.org $%04X' % SONG_RAM,
            'songTable:                        ; tune 0 (extra life, in PRG) is filled in by InitMusicPtr',
            '  .word 0' + ''.join(', %s+SONG_PTR_BIAS' % TUNE_NAMES[k] for k in (1, 2, 3))]
    labels[SONG_RAM] = ('songTable', 8, 'tune pointers as PPU addresses (RAM + SONG_PTR_BIAS); [0] set by InitMusicPtr')
    a = SONG_RAM + 8
    order = sorted(starts)
    assert order[0] == a and all(starts[s] in TUNE_NAMES for s in order)
    for n, s in enumerate(order):
        e = order[n + 1] if n + 1 < len(order) else SONG_RAM + SONG_SIZE
        data = blk[s - SONG_RAM:e - SONG_RAM]
        name = TUNE_NAMES[starts[s]]
        labels[s] = (name, e - s, 'tune %d' % starts[s])
        out.append('%-33s ; tune %d, %d notes' % (name + ':', starts[s], len(data) - 1))
        for k in range(0, len(data), 6):
            out.append('  .byte ' + ', '.join(note_expr(b, note_names, dur_names) for b in data[k:k + 6]))
    out += ['  .assert * = songTable+SONG_DATA_SIZE, error, "tune block must end at $0200"',
            '.reloc', '  .incbin "chr/chr_0.chr", CHR_SONGS+SONG_DATA_SIZE', '']

    # ---------------------------------------------------------------- texts
    blk = chr_[TEXT_CHR:TEXT_CHR + TEXT_SIZE]
    tbias = TEXT_CHR - TEXT_RAM
    ptrs = [blk[1 + 2 * k] | blk[2 + 2 * k] << 8 for k in range(TEXT_COUNT)]
    recs = {}                                   # ram addr -> label
    used = set()
    logo0, nlogo = consts.get('TXT_LOGO0', -1), consts.get('INTRO_LOGO_ROWS', 0)
    raw_idx = set(range(logo0, logo0 + nlogo)) | {consts.get('TXT_BORDER'), consts.get('TXT_LOGO_NAMCOT')}
    raw_addrs = {ptrs[k] - tbias for k in raw_idx if k is not None and 0 <= k < TEXT_COUNT}
    for k, p in enumerate(ptrs):
        r = p - tbias
        if r in recs:
            continue
        nm = 'Txt' + camel(txt_names[k][4:]) if k in txt_names else None
        if nm is None and logo0 <= k < logo0 + nlogo:
            nm = 'TxtLogo%d' % (k - logo0)
        for base, count, fmt in (('TXT_SCORE_ROW0', 4, 'TxtScoreRow%d'), ('TXT_BONUS_150', 4, None)):
            b = consts.get(base, -1)
            if nm is None and b <= k < b + count:
                body = blk[r - TEXT_RAM + 2:blk.index(TEXT_END, r - TEXT_RAM + 2)]
                nm = fmt % (k - b) if fmt else 'TxtBonus' + camel(shown(body, specials))
        if nm is None:
            body = blk[r - TEXT_RAM + 2:blk.index(TEXT_END, r - TEXT_RAM + 2)]
            nm = 'Txt' + (camel(shown(body, specials).replace('(c)', 'C')) or 'Blank')
        while nm in used:
            nm += '_'
        used.add(nm)
        recs[r] = nm
    out += ['  .incbin "chr/chr_1.chr", $0000, CHR_GAME_DATA-CHR_TABLE1', '',
            '; PPU $%04X-$%04X -> RAM $%04X-$%04X: text pointers (PPU addresses) + text records (PrintText)'
            % (TEXT_CHR, TEXT_CHR + TEXT_SIZE - 1, TEXT_RAM, TEXT_RAM + TEXT_SIZE - 1),
            '.charmap $20, $40                  ; normal font: tile = char - TEXT_BIAS_ASCII, space = $40',
            '.charmap $2D, $5B',
            '.charmap $2E, $5C',
            '.org $%04X' % TEXT_RAM,
            'chrData:',
            '  .byte $%02X                        ; unused' % blk[0],
            'textPtrs:                         ; PrintText: text number -> record, as a PPU address (RAM + TEXT_PTR_BIAS)']
    labels[TEXT_RAM] = ('chrData', 1, 'RAM copy of PPU $1480-$17FF: text pointers and records (src/chr.asm)')
    labels[TEXT_RAM + 1] = ('textPtrs', 2 * TEXT_COUNT, 'PrintText: 2-byte pointers to the texts, as PPU addresses')
    for k, p in enumerate(ptrs):
        out.append('  .word %-28s ; $%02X%s' % (recs[p - tbias] + '+TEXT_PTR_BIAS', k,
                                              (' ' + txt_names[k]) if k in txt_names else ''))
    a = TEXT_RAM + 1 + 2 * TEXT_COUNT
    end = TEXT_RAM + TEXT_SIZE
    while a < end:
        if a == TILES_RAM:
            out += ['chrTiles:                         ; tiles $%02X-$%02X: graphics (HUD icons), copied to RAM too'
                    % ((a + tbias - 0x1000) // 16, (TILES_END + tbias - 0x1000) // 16 - 1),
                    '  .incbin "chr/chr_1.chr", CHR_ICONS-CHR_TABLE1, $%X' % (TILES_END - TILES_RAM)]
            labels[a] = ('chrTiles', TILES_END - TILES_RAM, 'tiles $60-$6F (graphics) in the copied block')
            a = TILES_END
            continue
        if a in recs:
            i = a - TEXT_RAM
            e = blk.index(TEXT_END, i + 2)
            row, col, body = blk[i], blk[i + 1], blk[i + 2:e]
            labels[a] = (recs[a], e + 1 - i, 'text record')
            if a in raw_addrs:
                items = [hexbytes(body)] if body else []
                note = 'tiles (printed with textCharBias = 0)'
            else:
                items = text_parts(body, specials)
                note = '"%s"' % shown(body, specials)
            out.append('%-33s ; %s' % (recs[a] + ':', note))
            out.append('  .byte ' + ', '.join(['%d, %d' % (row, col)] + items + ['TEXT_END']))
            a += e + 1 - i
            continue
        # filler up to the next record / tile block
        nxt = min([r for r in recs if r > a] + [TILES_RAM if a < TILES_RAM else end, end])
        data = blk[a - TEXT_RAM:nxt - TEXT_RAM]
        if set(data) == {0xFF}:
            if nxt == TILES_RAM:
                out.append('  .res chrData+CHR_ICONS-CHR_GAME_DATA-*, $FF')
            elif nxt == end:
                out.append('  .res chrData+CHR_GAME_DATA_SIZE-*, $FF')
            else:
                out.append('  .res %d, $FF                     ; free' % len(data))
        else:
            out.append('  .byte ' + hexbytes(data) + '  ; unused')
        a = nxt
    out += ['  .assert * = chrData+CHR_GAME_DATA_SIZE, error, "text block must end at $0680"',
            '.charmap $20, $20',
            '.charmap $2D, $2D',
            '.charmap $2E, $2E',
            '.reloc',
            '  .incbin "chr/chr_1.chr", CHR_GAME_DATA+CHR_GAME_DATA_SIZE-CHR_TABLE1',
            '']
    return '\n'.join(out) + '\n', labels


def note_expr(b, note_names, dur_names):
    if b == 0xFF:
        return 'SONG_END'
    if b >> 5 not in dur_names or b & 0x1F not in note_names:
        return '$%02X' % b
    return '%s|%s' % (dur_names[b >> 5], note_names[b & 0x1F])
